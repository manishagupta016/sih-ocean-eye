/**
 * Reference taxonomy for underwater side-scan sonar (SSS) object identification, compiled for
 * SIH 2026 PS 26057. This is a knowledge/reference dataset for operators - it is independent of
 * (and broader than) the 5 classes the shipped classifier (app/ml/classifier.py) currently
 * recognizes. `matchesLabels` links a guide entry to the raw `class_label` strings the pipeline
 * actually emits today, where a reasonable correspondence exists; entries with no match are
 * classes the current model does not yet distinguish.
 */

