/** Raw pipeline `class_label` -> guide slug, for cross-linking a detection to its criteria. */
export const CLASS_LABEL_TO_GUIDE_SLUG: Record<string, string> = IDENTIFICATION_CLASSES.reduce(
  (acc, entry) => {
    for (const label of entry.matchesLabels) acc[label] = entry.slug
    return acc
  },
  {} as Record<string, string>,
)

